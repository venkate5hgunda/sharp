import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
async function walk(directory) {
  const entries = await readdir(path.join(root, directory), { withFileTypes: true });
  return (await Promise.all(entries.filter((entry) => !entry.name.startsWith('.')).map((entry) => {
    const relative = path.posix.join(directory, entry.name);
    return entry.isDirectory() ? walk(relative) : [relative];
  }))).flat();
}
export async function generateManifest() {
  const assets = ['index.html', 'manifest.json', ...(await walk('js')), ...(await walk('data')),
    ...(await walk('css')), ...(await walk('assets'))].sort();
  const digest = createHash('sha256');
  for (const name of [...assets, 'sw.js']) {
    digest.update(name).update('\0').update(await readFile(path.join(root, name))).update('\0');
  }
  return '// Generated by npm run build:offline. Do not edit.\nself.SHARP_OFFLINE = ' +
    JSON.stringify({ version: digest.digest('hex').slice(0, 20), assets }, null, 2) + ';\n';
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = await generateManifest();
  const destination = path.join(root, 'offline-manifest.js');
  if (process.argv.includes('--check')) {
    if (await readFile(destination, 'utf8').catch(() => '') !== output) {
      console.error('Offline manifest is stale. Run npm run build:offline.');
      process.exitCode = 1;
    }
  } else {
    await writeFile(destination, output);
  }
}
